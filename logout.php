<?php
// ==========================================================
//  ログアウト処理（画面なし）
//  授業で習った「セッションの終了」の3手順をそのまま実行する。
//   ① セッション変数を空にする
//   ② ブラウザに保存されたセッションCookieを無効化する
//   ③ セッション領域自体を破棄する
// ==========================================================

session_start();

// ① セッション変数を全部空にする
$_SESSION = array();

// ② セッションCookieの有効期限を過去にして無効化する
if (isset($_COOKIE[session_name()])) {
    setcookie(session_name(), '', time() - 42000, '/');
}

// ③ セッション領域を破棄する
session_destroy();

// TOPへ戻る（未ログイン状態になっている）
header('Location: top.php');
exit;
