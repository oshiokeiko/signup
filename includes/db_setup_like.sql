--  いいね機能のためのテーブル作成＋記事データ投入
--
--  【使い方】
--   1. XAMPP を起動し、http://localhost/phpmyadmin を開く
--   2. 左のリストから member_system_db を選ぶ
--   3. 上の「SQL」タブを開き、このファイルの中身を全部貼り付けて実行
--
--  ※ IF NOT EXISTS を付けているので、間違って2回実行しても
--     既にある表を壊すことはありません。
--  ※ 記事データの INSERT は、2回実行すると重複します。
--     その場合は「-- 記事データ」より下だけを実行しないでください。
-- ============================================================


-- ------------------------------------------------------------
--  articles … 記事テーブル
--   intro … 誰でも読める冒頭（ペイウォールの手前）
--   body  … 会員だけ読める続き。段落は「空行」で区切って保存する
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS articles (
  id          INT(11)      NOT NULL AUTO_INCREMENT,
  title       VARCHAR(255) NOT NULL,
  intro       TEXT         NOT NULL,
  body        TEXT         NOT NULL,
  created_at  DATETIME     DEFAULT NULL,
  updated_at  DATETIME     DEFAULT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


-- ------------------------------------------------------------
--  like_table … いいねテーブル（中間テーブル）
--   「どの会員が」「どの記事に」いいねしたかを1行ずつ記録する
--   user_id    … users.id に対応
--   article_id … articles.id に対応
--
--  UNIQUE KEY は「同じ会員が同じ記事に2行入らない」ための保険。
--  1人1いいねの判定は PHP 側（COUNT）で行うが、連打などで
--  すり抜けた場合もデータベース側で二重登録を防げる。
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS like_table (
  id          INT(11)  NOT NULL AUTO_INCREMENT,
  user_id     INT(11)  NOT NULL,
  article_id  INT(11)  NOT NULL,
  created_at  DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_user_article (user_id, article_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


