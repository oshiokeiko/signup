<?php
// ==========================================================
//  ログイン関連の共通関数
//  ・is_login()    … ログインしているか true/false を返す（追い返さない）
//  ・check_login() … ログイン必須ページで使う（未ログインなら追い返す）
//  ※ これらを使うページでは、必ず先に session_start() を実行しておくこと。
// ==========================================================

// --------------------------------------------------
//  ログインしているかを true / false で返す
//  記事ページ(article.php)の「見せ方の出し分け」に使う。
//  条件：セッションに session_id があり、かつ現在の session_id と一致する
// --------------------------------------------------
function is_login()
{
    return isset($_SESSION['session_id']) && $_SESSION['session_id'] === session_id();
}

// --------------------------------------------------
//  ログイン必須ページの入口で実行する“門番”。
//  ・未ログイン → login.php へ強制移動（URL直打ち対策）
//  ・ログイン済 → session_id を作り直し、$_SESSION を最新に保つ
//    （session_id を毎回更新することで、盗まれた古い id を無効化する）
// --------------------------------------------------
function check_login()
{
    if (!is_login()) {
        header('Location: login.php');
        exit;
    }
    // ログイン済みなら id を再生成して最新化（true で古い id を無効化）
    session_regenerate_id(true);
    $_SESSION['session_id'] = session_id();
}
